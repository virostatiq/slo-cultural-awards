#!/usr/bin/env python3
"""List suspicious records for manual review -> docs/review/data-issues.md.

Re-runnable: it reads the current data/ tables, so fixed issues drop off the list.

    uv run python scripts/data_issues.py
"""

import re
import pandas as pd

from kulturne_nagrade import PROJECT_ROOT, frames

OUT = PROJECT_ROOT / "docs" / "review" / "data-issues.md"


TITLES = {"dr", "mag", "prof", "akad", "izr"}


def first_name(name: str) -> str:
    parts = [p for p in name.lower().split() if p.rstrip(".") not in TITLES]
    return (parts or [""])[0].rstrip(".")


def main() -> None:
    r = frames.roles(entity_types=None)
    ent = frames.entities().set_index("entity_id")
    lines = ["# Review: suspicious records", "",
             "Generated by `scripts/data_issues.py` from the current data. Re-run after fixes.", ""]

    post = (r[r["posthumous"]].sort_values(["year"])
            [["entity_id", "name", "award", "year", "role", "year_death", "year_birth_source"]])
    lines += ["## Credited after death", "",
              ("Either a posthumous honour (a picture book of Cankar's text, a lifetime award "
              "announced after death) or the enrichment matched the wrong person and the "
              "death year (maybe the birth year too) is wrong. For a wrong match, clear "
              "the life dates in `entities.csv`."), "",
              "| entity_id | award | year | role | died | birth-year source | verdict |",
              "|---|---|---|---|---|---|---|"]
    lines += [f"| `{x.entity_id}` | {x.award} | {x.year} | {x.role} | {x.year_death} "
              f"| {x.year_birth_source or '—'} | |" for x in post.itertuples()]

    titled = ent[ent["name"].str.match(r"^(dr|mag|prof|akad|izr)\.?\s", case=False)]
    lines += ["", "## Academic titles in names", "",
              "Names should not carry titles. Rename, and keep the titled form as an alias.", ""]
    lines += [f"- `{i}`: {n}" for i, n in titled["name"].items()] or ["- none"]

    # Merges whose first names differ in a gendered way (Damjan/Damjana) or at all.
    al = frames.table("aliases").merge(ent["name"], left_on="entity_id", right_index=True)
    # aliases added by the resolved-names review are decided already
    log = PROJECT_ROOT / "data" / "meta" / "name_decisions.csv"
    reviewed = set()
    if log.exists():
        nd = pd.read_csv(log)
        reviewed = set(nd.loc[nd["action"] == "alias", "detail"])
    sus = []
    for a in al.itertuples():
        if a.alias in reviewed:
            continue
        fa, fc = first_name(a.alias), first_name(a.name)
        if fa != fc and (fa.rstrip("a") == fc.rstrip("a") or not re.sub(r"[^a-z]", "", fa)
                         .startswith(re.sub(r"[^a-z]", "", fc)[:3])):
            sus.append((a.alias, a.name, a.entity_id))
    lines += ["", "## Merges with differing first names", "",
              ("Legacy merges where the first names differ, e.g. a gendered form "
              "(Damjan/Damjana). Some are real diminutives; others merged two people. "
              "To undo one: add the alias back as its own entity and move its roles."), "",
              "| alias | merged into | entity_id | same person? |", "|---|---|---|---|"]
    lines += [f"| {a} | {n} | `{i}` | |" for a, n, i in sorted(sus)]

    odd = jury_size_outliers(r)
    lines += ["", "## Unusual jury sizes", "",
              ("Editions whose recorded jury is much smaller or larger than the same award's "
              "juries in the surrounding years (±10): at most half or at least double the "
              "median of at least 3 other editions (and at least 2 members off), or 1–2 "
              "members where that median is 4 "
              "or more. Usually a partial or merged jury list; sometimes a real change of "
              "rules. Editions with no jury are not listed (see the coverage theme)."), "",
              "| edition_id | jurors | award median (±10 y) | verdict |", "|---|---|---|---|"]
    lines += [f"| `{x.edition_id}` | {x.size} | {x.median:g} | |" for x in odd.itertuples()]

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(PROJECT_ROOT)}: {len(post)} posthumous, {len(titled)} titled, "
          f"{len(sus)} suspect merges, {len(odd)} unusual jury sizes")


def jury_size_outliers(r: pd.DataFrame, window: int = 10) -> pd.DataFrame:
    """Legacy plot 23 (jury size consistency) as a review list: it flagged ±2σ around a
    whole-history mean and counted missing juries as size 0."""
    size = (r[r["role"] == "jury"].groupby(["edition_id", "award_id", "year"]).size()
            .rename("size").reset_index())
    rows = []
    for x in size.itertuples():
        other = size[(size["award_id"] == x.award_id) & (size["edition_id"] != x.edition_id)
                     & size["year"].between(x.year - window, x.year + window)]
        if len(other) < 3:
            continue
        med = float(other["size"].median())
        ratio_off = (x.size <= med / 2 or x.size >= 2 * med) and abs(x.size - med) >= 2
        if ratio_off or (x.size <= 2 and med >= 4):
            rows.append({"edition_id": x.edition_id, "size": int(x.size), "median": med})
    return pd.DataFrame(rows, columns=["edition_id", "size", "median"]).sort_values(
        "edition_id")


if __name__ == "__main__":
    main()
